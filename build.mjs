// Static site builder for sprintmicrocredit.com — no dependencies, Node 18+.
//
//   node build.mjs           -> builds ./dist
//   node build.mjs --serve   -> builds, then serves ./dist on http://localhost:8080
//
// Pages live in src/pages. Each starts with a JSON front-matter block between
// `---` lines, followed by the page body HTML. `{{site.x}}` / `{{page.x}}`
// tokens are replaced at build time. src/site.json is the single source of
// truth for business facts (phone, address, calculator defaults, ...).

import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'node:http';
import { createHash } from 'node:crypto';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'dist');
const site = JSON.parse(readFileSync(join(SRC, 'site.json'), 'utf8'));
const today = new Date().toISOString().slice(0, 10);

const partial = (name) => readFileSync(join(SRC, 'partials', `${name}.html`), 'utf8');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const stripTags = (s) => s.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();

// Responsive photos generated by tools/optimize_photos.py.
const photos = JSON.parse(readFileSync(join(SRC, 'photos.json'), 'utf8'));
const icons = new Set([...partial('icons').matchAll(/id="i-([\w-]+)"/g)].map((m) => m[1]));
const photoUrl = (slug, w, ext) => `/assets/img/photos/${slug}-${w}.${ext}`;

// `<!--img src="slug" alt="…" sizes="…" class="…" pos="50% 30%" eager-->` -> <picture> with
// WebP + JPG/PNG srcsets, intrinsic size (no layout shift) and lazy loading unless `eager`.
function picture(attrs) {
  const p = photos[attrs.src];
  if (!p) throw new Error(`Unknown photo "${attrs.src}" (run tools/optimize_photos.py)`);
  if (attrs.alt === undefined) throw new Error(`Photo "${attrs.src}" needs alt text`);
  const ext = p.alpha ? 'png' : 'jpg';
  const sizes = attrs.sizes || '100vw';
  const set = (e) => p.widths.map((w) => `${photoUrl(attrs.src, w, e)} ${w}w`).join(', ');
  const fallback = photoUrl(attrs.src, p.widths[Math.min(1, p.widths.length - 1)], ext);
  const loading = 'eager' in attrs ? 'fetchpriority="high"' : 'loading="lazy"';
  const style = attrs.pos ? ` style="object-position:${attrs.pos}"` : '';
  return `<picture${attrs.class ? ` class="${attrs.class}"` : ''}>` +
    `<source type="image/webp" srcset="${set('webp')}" sizes="${sizes}">` +
    `<img src="${fallback}" srcset="${set(ext)}" sizes="${sizes}" width="${p.w}" height="${p.h}" alt="${attrs.alt}" ${loading} decoding="async"${style}>` +
    `</picture>`;
}

function render(template, ctx) {
  // `<!--include:name-->` pulls in src/partials/name.html (one level deep).
  template = template.replace(/<!--include:([\w-]+)-->/g, (m, name) => partial(name));
  template = template.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (m, key) => {
    const val = key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), ctx);
    if (val === undefined) throw new Error(`Unknown template token ${m}`);
    return val;
  });
  // `<!--icon name-->` -> inline reference to the SVG sprite in partials/icons.html
  template = template.replace(/<!--icon ([\w-]+)-->/g, (m, name) => {
    if (!icons.has(name)) throw new Error(`Unknown icon "${name}"`);
    return `<svg class="i" aria-hidden="true"><use href="#i-${name}"/></svg>`;
  });
  return template.replace(/<!--img\s([\s\S]*?)-->/g, (m, raw) => {
    const attrs = {};
    for (const [, k, v] of raw.matchAll(/([\w-]+)(?:="([^"]*)")?/g)) attrs[k] = v ?? '';
    return picture(attrs);
  });
}

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

function parsePage(file) {
  const raw = readFileSync(file, 'utf8');
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!m) throw new Error(`Missing front matter in ${file}`);
  const meta = JSON.parse(m[1]);
  return { ...meta, body: raw.slice(m[0].length), file };
}

// ---------- Structured data ----------

const orgId = `${site.url}/#organization`;

function businessSchema() {
  return {
    '@type': ['FinancialService', 'LocalBusiness'],
    '@id': orgId,
    name: site.name,
    legalName: site.legalName,
    slogan: site.tagline,
    description: 'Quick, same-day emergency loans for salaried workers in Ghana, especially staff of financial institutions and state-owned enterprises (SOEs).',
    url: site.url,
    logo: `${site.url}/assets/img/logo-sprint.png`,
    image: `${site.url}/assets/img/og-image.png`,
    telephone: site.phoneIntl,
    email: site.email,
    foundingDate: site.foundingYear,
    currenciesAccepted: 'GHS',
    areaServed: { '@type': 'Country', name: 'Ghana' },
    address: {
      '@type': 'PostalAddress',
      streetAddress: site.address.street,
      addressLocality: `${site.address.locality}, ${site.address.city}`,
      addressRegion: site.address.region,
      addressCountry: site.address.country,
    },
    openingHoursSpecification: site.hours.map((h) => ({
      '@type': 'OpeningHoursSpecification', dayOfWeek: h.days, opens: h.opens, closes: h.closes,
    })),
    sameAs: [site.facebook, site.linkedin],
    memberOf: { '@type': 'Organization', name: site.association },
    founder: { '@type': 'Person', name: site.founder.name, jobTitle: site.founder.title },
  };
}

function faqSchema(body) {
  const items = [...body.matchAll(/<details class="faq-item"[^>]*>\s*<summary>([\s\S]*?)<\/summary>([\s\S]*?)<\/details>/g)];
  if (!items.length) return null;
  return {
    '@type': 'FAQPage',
    mainEntity: items.map(([, q, a]) => ({
      '@type': 'Question', name: stripTags(q),
      acceptedAnswer: { '@type': 'Answer', text: stripTags(a) },
    })),
  };
}

function breadcrumbSchema(page) {
  if (!page.crumbs) return null;
  const list = [['Home', '/'], ...page.crumbs];
  return {
    '@type': 'BreadcrumbList',
    itemListElement: list.map(([name, path], i) => ({
      '@type': 'ListItem', position: i + 1, name, item: site.url + path,
    })),
  };
}

function articleSchema(page) {
  if (!page.article) return null;
  return {
    '@type': 'Article',
    headline: page.h1 || page.title,
    description: page.description,
    datePublished: page.published,
    dateModified: page.modified || page.published,
    inLanguage: 'en-GH',
    mainEntityOfPage: site.url + page.path,
    image: ogImageFor(page).url,
    author: { '@id': orgId },
    publisher: { '@id': orgId },
  };
}

// Social share image: the page's own photo when it has one, else the branded card.
function ogImageFor(page) {
  const p = page.image && photos[page.image];
  if (!p) return { url: `${site.url}/assets/img/og-image.png`, w: 1200, h: 630 };
  const w = [...p.widths].reverse().find((x) => x <= 1200) || p.widths[0];
  return { url: site.url + photoUrl(page.image, w, p.alpha ? 'png' : 'jpg'), w, h: Math.round((p.h * w) / p.w) };
}

function schemaFor(page) {
  const graph = [businessSchema()];
  if (page.path === '/') {
    graph.push({ '@type': 'WebSite', '@id': `${site.url}/#website`, url: site.url, name: site.name, inLanguage: 'en-GH', publisher: { '@id': orgId } });
  }
  if (page.product) {
    graph.push({
      '@type': 'LoanOrCredit',
      name: page.product,
      provider: { '@id': orgId },
      areaServed: 'GH',
      currency: 'GHS',
      amount: { '@type': 'MonetaryAmount', currency: 'GHS', minValue: site.calc.min, maxValue: site.calc.max },
      loanTerm: { '@type': 'QuantitativeValue', minValue: site.calc.minMonths, maxValue: site.calc.maxMonths, unitCode: 'MON' },
    });
  }
  for (const s of [faqSchema(page.body), breadcrumbSchema(page), articleSchema(page)]) if (s) graph.push(s);
  return JSON.stringify({ '@context': 'https://schema.org', '@graph': graph });
}

// ---------- Build ----------

function breadcrumbHtml(page) {
  if (!page.crumbs) return '';
  const list = [['Home', '/'], ...page.crumbs];
  const items = list.map(([name, path], i) =>
    i === list.length - 1
      ? `<li aria-current="page">${esc(name)}</li>`
      : `<li><a href="${path}">${esc(name)}</a></li>`).join('');
  return `<nav class="crumbs container" aria-label="Breadcrumb"><ol>${items}</ol></nav>`;
}

function markActiveNav(html, path) {
  // Mark the nav link whose section contains the current path.
  return html.replace(/<a class="nav-link" href="([^"]+)"/g, (m, href) => {
    const active = href === '/' ? path === '/' : path.startsWith(href);
    return active ? `<a class="nav-link" aria-current="page" href="${href}"` : m;
  });
}

function build() {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  cpSync(join(SRC, 'public'), OUT, { recursive: true });

  const year = String(new Date().getFullYear());
  const ghs = (n) => `GH₵${n.toLocaleString('en-US')}`;
  // Worked example for the "What you'll pay" section, always computed from the current rate
  const ex = { P: 1000, n: 6 };
  ex.interest = ex.P * (site.calc.monthlyRatePct / 100) * ex.n;
  ex.total = ex.P + ex.interest;
  const ghs2 = (n) => (Number.isInteger(n) ? ghs(n) : `GH₵${n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`);
  const fmt = {
    min: ghs(site.calc.min), max: ghs(site.calc.max),
    exP: ghs(ex.P), exN: ex.n, exInterest: ghs2(ex.interest), exTotal: ghs2(ex.total), exMonthly: ghs2(ex.total / ex.n),
    exPct: +(site.calc.monthlyRatePct * ex.n).toFixed(2),
  };
  const siteCtx = { ...site, year, logo: photos._logo, fmt, waLink: `https://wa.me/${site.whatsapp}`, mapEmbed: encodeURIComponent(site.mapQuery) };

  // Client-side config is generated from site.json so numbers never drift.
  writeFileSync(join(OUT, 'assets/js/config.js'),
    `window.SPRINT=${JSON.stringify({ name: site.name, whatsapp: site.whatsapp, phoneIntl: site.phoneIntl, email: site.email, calc: site.calc, hours: site.hours })};\n`);

  // Cache-busting: CSS/JS URLs carry a fingerprint of their contents, so they can be cached for a
  // year yet any change is picked up immediately (see the Cache-Control rules in vercel.json).
  const fingerprint = (rel) => createHash('sha256').update(readFileSync(join(OUT, rel))).digest('hex').slice(0, 10);
  siteCtx.v = { css: fingerprint('assets/css/styles.css'), js: fingerprint('assets/js/main.js'), config: fingerprint('assets/js/config.js') };

  const pages = walk(join(SRC, 'pages')).filter((f) => f.endsWith('.html')).map(parsePage);
  const head = partial('head'), header = partial('header'), footer = partial('footer');

  for (const page of pages) {
    const ctx = { site: siteCtx, page: { ...page, canonical: site.url + page.path, robots: page.noindex ? 'noindex, follow' : 'index, follow, max-image-preview:large', og: ogImageFor(page), ogType: page.article ? 'article' : 'website' } };
    const body = render(page.body, ctx);
    const html = [
      '<!doctype html>\n<html lang="en-GH">\n<head>',
      render(head, ctx),
      `<script type="application/ld+json">${schemaFor({ ...page, body })}</script>`,
      '</head>',
      `<body class="${page.bodyClass || ''}">`,
      markActiveNav(render(header, ctx), page.path),
      `<main id="main">${breadcrumbHtml(page)}${body}</main>`,
      render(footer, ctx),
      '</body>\n</html>\n',
    ].join('\n');
    const outFile = page.outFile ? join(OUT, page.outFile) : join(OUT, page.path, 'index.html');
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, html);
  }

  const indexable = pages.filter((p) => !p.noindex);
  writeFileSync(join(OUT, 'sitemap.xml'),
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    indexable.map((p) => `  <url><loc>${site.url}${p.path}</loc><lastmod>${p.modified || p.published || today}</lastmod><priority>${p.priority || '0.7'}</priority></url>`).join('\n') +
    `\n</urlset>\n`);
  writeFileSync(join(OUT, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site.url}/sitemap.xml\n`);

  checkCsp();
  console.log(`Built ${pages.length} pages -> dist/`);
}

// Every inline <script> in the output must be allowed by the CSP hash in vercel.json and .htaccess,
// otherwise browsers would silently block it in production.
function checkCsp() {
  const policies = {
    'vercel.json': JSON.parse(readFileSync(join(ROOT, 'vercel.json'), 'utf8')).headers
      .flatMap((h) => h.headers).find((h) => h.key === 'Content-Security-Policy')?.value || '',
    '.htaccess': readFileSync(join(SRC, 'public', '.htaccess'), 'utf8'),
  };
  const hashes = new Set();
  for (const f of walk(OUT).filter((p) => p.endsWith('.html'))) {
    for (const [, attrs, body] of readFileSync(f, 'utf8').matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
      if (/\bsrc=|application\/ld\+json/.test(attrs)) continue; // external files and JSON-LD data are fine
      hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`);
    }
  }
  for (const h of hashes) {
    for (const [file, policy] of Object.entries(policies)) {
      if (!policy.includes(h)) throw new Error(`Inline script hash ${h} is missing from the Content-Security-Policy in ${file}`);
    }
  }
}

// Local preview applies the same response headers as vercel.json, so CSP problems show up before deploying.
const vercelHeaders = () => JSON.parse(readFileSync(join(ROOT, 'vercel.json'), 'utf8')).headers || [];

function serve(port = 8080) {
  const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.svg': 'image/svg+xml', '.png': 'image/png', '.xml': 'application/xml', '.txt': 'text/plain', '.webmanifest': 'application/manifest+json', '.ico': 'image/x-icon' };
  createServer((req, res) => {
    let p = join(OUT, decodeURIComponent(req.url.split('?')[0]));
    if (existsSync(p) && statSync(p).isDirectory()) p = join(p, 'index.html');
    if (!existsSync(p)) { res.writeHead(404, { 'Content-Type': types['.html'] }); return res.end(readFileSync(join(OUT, '404.html'))); }
    const headers = { 'Content-Type': types[extname(p)] || 'application/octet-stream' };
    for (const rule of vercelHeaders()) {
      if (new RegExp(`^${rule.source}$`).test(req.url.split('?')[0])) for (const h of rule.headers) headers[h.key] = h.value;
    }
    res.writeHead(200, headers);
    res.end(readFileSync(p));
  }).listen(port, () => console.log(`Serving dist/ on http://localhost:${port}`));
}

build();
if (process.argv.includes('--serve')) serve(Number(process.env.PORT) || 8080);
